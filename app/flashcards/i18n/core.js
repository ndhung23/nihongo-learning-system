const placeholderPattern = /\{([a-zA-Z][a-zA-Z0-9]*)\}/g;

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function compileTemplate(template) {
  const names = [];
  let lastIndex = 0;
  let source = "^";

  for (const match of template.matchAll(placeholderPattern)) {
    source += escapeRegExp(template.slice(lastIndex, match.index));
    const valuePattern = {
      count: "[0-9]+(?:[.,][0-9]+)*",
      current: "[0-9]+(?:[.,][0-9]+)*",
      target: "[0-9]+(?:[.,][0-9]+)*",
      lesson: "[0-9]+",
      level: "[a-zA-Z0-9]+",
      range: "[0-9]+\\s*[-–]\\s*[0-9]+",
    }[match[1]] || ".+?";
    source += `(${valuePattern})`;
    names.push(match[1]);
    lastIndex = (match.index || 0) + match[0].length;
  }

  source += `${escapeRegExp(template.slice(lastIndex))}$`;
  return { names, pattern: new RegExp(source, "u") };
}

const messageTranslations = Object.keys(messages.vi).map((key) => [messages.vi[key], messages.en[key]]);
const translations = [...messageTranslations, ...uiTranslations].map(([vi, en]) => ({
  vi,
  en,
  viTemplate: compileTemplate(vi),
  enTemplate: compileTemplate(en),
}));
const translationsBySource = {
  vi: [...translations].sort((left, right) => right.vi.replace(placeholderPattern, "").length - left.vi.replace(placeholderPattern, "").length),
  en: [...translations].sort((left, right) => right.en.replace(placeholderPattern, "").length - left.en.replace(placeholderPattern, "").length),
};

export function isSupportedLocale(value) {
  return SUPPORTED_LOCALES.includes(value);
}

export function resolveLocale(savedLocale, browserLocale = "vi") {
  if (isSupportedLocale(savedLocale)) return savedLocale;
  return String(browserLocale).toLowerCase().startsWith("en") ? "en" : "vi";
}

export function getMessage(locale, key) {
  return messages[isSupportedLocale(locale) ? locale : "vi"][key] || messages.vi[key] || key;
}

function renderTemplate(target, sourceTemplate, match) {
  const values = Object.fromEntries(sourceTemplate.names.map((name, index) => [name, match[index + 1]]));
  const rendered = target.replace(placeholderPattern, (_, name) => values[name] ?? "");
  if (Number(values.count) !== 1) return rendered;

  return rendered
    .replace(/\bactive courses\b/u, "active course")
    .replace(/\bcorrect answers\b/u, "correct answer")
    .replace(/\btest questions\b/u, "test question")
    .replace(/\bvocabulary words\b/u, "vocabulary word")
    .replace(/\b(characters|learners|lessons|missions|questions|sections|tickets|words|coins|days)\b/u, (value) => value.slice(0, -1));
}

function translateTrimmed(value, locale) {
  const sourceLocale = locale === "en" ? "vi" : "en";
  for (const translation of translationsBySource[sourceLocale]) {
    if (value === translation[locale]) return value;
    const sourceTemplate = translation[`${sourceLocale}Template`];
    const match = value.match(sourceTemplate.pattern);
    if (match) return renderTemplate(translation[locale], sourceTemplate, match);
  }

  return value;
}

export function translateUiText(value, locale) {
  if (typeof value !== "string" || !value) return value;
  const leading = value.match(/^\s*/u)?.[0] || "";
  const trailing = value.match(/\s*$/u)?.[0] || "";
  const trimmed = value.slice(leading.length, value.length - trailing.length);
  if (!trimmed) return value;
  return `${leading}${translateTrimmed(trimmed, isSupportedLocale(locale) ? locale : "vi")}${trailing}`;
}

export function getTranslationDiagnostics() {
  const duplicateVietnamese = uiTranslations
    .map(([vi]) => vi)
    .filter((value, index, values) => values.indexOf(value) !== index);
  const duplicateEnglish = uiTranslations
    .map(([, en]) => en)
    .filter((value, index, values) => values.indexOf(value) !== index);
  return { duplicateVietnamese, duplicateEnglish };
}
